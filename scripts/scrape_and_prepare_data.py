def get_match_time(footballbox):
    fright = footballbox.find("div", class_="fright")

    if fright is None:
        return None

    text = fright.get_text(" ", strip=True)

    time_match = re.search(
        r"(\d{1,2}:\d{2})\s*([صم])",
        text
    )

    if time_match is None:
        return None

    clock = time_match.group(1)
    period = time_match.group(2)

    hour, minute = map(int, clock.split(":"))

    if period == "م" and hour != 12:
        hour += 12

    if period == "ص" and hour == 12:
        hour = 0

    return f"{hour:02d}:{minute:02d}"


