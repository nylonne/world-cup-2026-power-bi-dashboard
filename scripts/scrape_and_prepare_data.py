def parse_goals(goal_cell):
    if goal_cell is None:
        return []

    player_links = [
        link for link in goal_cell.find_all("a")
        if not re.fullmatch(
            r"[\d+\s']+",
            link.get_text(" ", strip=True)
        )
    ]

    player_names = [
        link.get_text(" ", strip=True)
        for link in player_links
    ]

    player_url_map = {
        link.get_text(" ", strip=True): link.get("href")
        for link in player_links
    }

    goal_items = list(goal_cell.stripped_strings)

    goals_list = []
    current_player = None

    for item in goal_items:
        text = item.strip()

        # -------------------------
        # Player
        # -------------------------
        if text in player_names:
            current_player = text
            continue

