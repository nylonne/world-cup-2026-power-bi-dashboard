def get_player_image_fallback(player_url):
    try:
        response = session.get(
            player_url,
            timeout=(5, 10)
        )

        if response.status_code != 200:
            return None

        soup = BeautifulSoup(
            response.text,
            "html.parser"
        )

        # Try infobox image
        infobox = soup.find(
            "table",
            class_="infobox"
        )

        if infobox:
            img = infobox.find("img")

            if img:
                src = img.get("src")

                if src:
                    return urljoin(
                        "https://ar.wikipedia.org",
                        src
                    )

        # Fallback: OpenGraph image
        og_image = soup.find(
            "meta",
            property="og:image"
        )

        if og_image:
            return og_image.get("content")

        return None

    except Exception as e:
        print("Error:", player_url, "->", e)
        return None

