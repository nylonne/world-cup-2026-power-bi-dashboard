def split_score(score):

    if pd.isna(score):
        return pd.Series([None, None])

    numbers = re.findall(r"\d+", str(score))

    if len(numbers) >= 2:
        return pd.Series([
            int(numbers[0]),
            int(numbers[1])
        ])

    return pd.Series([None, None])


