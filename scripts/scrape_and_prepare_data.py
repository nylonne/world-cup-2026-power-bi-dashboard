def get_correct_score(match):
    score_numbers = re.findall(r"\d+", match["Score"])

    if len(score_numbers) < 2:
        return match["Score"]

    first = int(score_numbers[0])
    second = int(score_numbers[1])

    home_goals = len(match["Home Goals"])
    away_goals = len(match["Away Goals"])

    # Normal orientation
    if first == home_goals and second == away_goals:
        return f"{first}-{second}"

    # RTL reversed orientation
    if second == home_goals and first == away_goals:
        return f"{second}-{first}"

    # Leave untouched if neither matches
    return match["Score"]


